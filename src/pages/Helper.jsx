function randomIdea() {
  const sec = SECTIONS[Math.floor(Math.random() * SECTIONS.length)];
  const list = IDEAS[sec.key];
  const idea = list[Math.floor(Math.random() * list.length)];
  return `💡 ${sec.en} (${sec.kk}) идеясы:\n${idea}\n\nСабақта қолданып көріп, видеоны «+» арқылы бөлісіңіз!`;
}

function answer(text) {
  const t = text.toLowerCase();
  if (/идея|ой |тапсырма|не істе|сабаққа|тәжірибе/.test(t)) return randomIdea();
  const hit = FAQ.find((f) => f.re.test(t));
  if (hit) return hit.a;
  return 'Кешіріңіз, бұл сұраққа жауап таба алмадым 🙈 Төмендегі сұрақтардың бірін таңдаңыз немесе жоба авторына хабарласыңыз: ' + SCHOOL.phone;
}

export default function Helper() {
  const { status } = useAuth();
  const [msgs, setMsgs] = useState([
    { from: 'bot', text: 'Сәлем! Мен — Shorts STEAM Lab көмекшісімін 🤖\nСұрақты таңдаңыз немесе төменге жазыңыз. Сабаққа жаңа идея керек болса, «Идея беріңізші!» батырмасын басыңыз.' },
  ]);
  const [input, setInput] = useState('');
  const end = useRef(null);

  useEffect(() => {
    end.current?.scrollIntoView({ behavior: 'smooth', block: 'end' });
  }, [msgs.length]);

  const ask = (text, reply) => {
    if (!text.trim()) return;
    setMsgs((m) => [...m, { from: 'me', text }]);
    setTimeout(() => setMsgs((m) => [...m, { from: 'bot', text: reply || answer(text) }]), 320);
  };

  return (
    <div className="wrap">
      {status !== 'ready' && <a className="back-btn" href="#/"><ArrowLeft size={18} /> Артқа</a>}
      <div className="rcard bot-head mt-16">
        <img src={ICONS.robot} alt="" />
        <div>
          <h1 className="h2">Көмекші</h1>
          <div className="muted" style={{ fontWeight: 700, fontSize: 14 }}>Жиі қойылатын сұрақтар және сабаққа идеялар</div>
        </div>
      </div>

      <div className="chat mt-12">
        {msgs.map((m, i) => (
          <div key={i} className={`bubble ${m.from}`}>{m.text}</div>
        ))}
        <div ref={end} />
      </div>

      <div className="qchips">
        <button className="qchip" onClick={() => ask('Идея беріңізші!', randomIdea())}>💡 Идея беріңізші!</button>
        {FAQ.map((f) => (
          <button key={f.q} className="qchip" onClick={() => ask(f.q, f.a)}>{f.q}</button>
        ))}
      </div>

      <form
        className="chat-input mt-16"
        onSubmit={(e) => {
          e.preventDefault();
          ask(input);
          setInput('');
        }}
      >
        <input className="input" value={input} onChange={(e) => setInput(e.target.value)} placeholder="Сұрағыңызды жазыңыз…" />
        <button className="btn btn-orange" aria-label="Жіберу"><Send /></button>
      </form>
    </div>
  );
}
